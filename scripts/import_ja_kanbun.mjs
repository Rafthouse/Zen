// Map slugs to their Japanese titles
const slugToJa = {
  'guteis_finger': '倶胝竪指',
  'hyakujos_fox': '百丈野狐',
  'joshus_dog_mu': '趙州狗子',
};

let imported = 0;
for (const k of koans) {
  const slug = k.id || k.slug;
  if (!slug || !k.text?.ja) continue;
  
  const jaTitle = k.title?.ja;
  if (!jaTitle || !jaTexts[jaTitle]) continue;
  
  k.text.ja.text = jaTexts[jaTitle];
  imported++;
}

writeFileSync(resolve(__dirname, '..', 'src', 'data', 'koans.json'), JSON.stringify(koans, null, 2), 'utf8');
console.log(`Imported Japanese kanbun text for ${imported} koans`);
